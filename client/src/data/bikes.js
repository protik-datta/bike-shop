/** Helper: filter mock bikes by flags (mirrors server query params) */
export function filterMockBikes(filters = {}) {
  let result = [...MOCK_BIKES];

  if (filters.brand)        result = result.filter((b) => b.brand === filters.brand);
  if (filters.category)     result = result.filter((b) => b.category.slug === filters.category || b.category._id === filters.category);
  if (filters.isFeatured)   result = result.filter((b) => b.isFeatured);
  if (filters.isNewArrival) result = result.filter((b) => b.isNewArrival);
  if (filters.isTopSelling) result = result.filter((b) => b.isTopSelling);
  if (filters.isHotDeal)    result = result.filter((b) => b.isHotDeal);
  if (filters.isPopular)    result = result.filter((b) => b.isPopular);
  if (filters.isSale)       result = result.filter((b) => b.isSale);
  if (filters.minPrice)     result = result.filter((b) => b.price >= Number(filters.minPrice));
  if (filters.maxPrice)     result = result.filter((b) => b.price <= Number(filters.maxPrice));
  if (filters.minCC)        result = result.filter((b) => b.engineCC >= Number(filters.minCC));
  if (filters.maxCC)        result = result.filter((b) => b.engineCC <= Number(filters.maxCC));
  if (filters.search)       result = result.filter((b) => b.name.toLowerCase().includes(filters.search.toLowerCase()) || b.brand.toLowerCase().includes(filters.search.toLowerCase()));

  return result;
}
